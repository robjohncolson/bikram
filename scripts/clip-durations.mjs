#!/usr/bin/env node
/**
 * Measures every recorded voice clip in public/voice with ffprobe and
 * regenerates src/pacer/clipdurations.ts, so the class can start a
 * movement the moment its line has been said. Rerun after
 * generate-voice.mjs. Requires ffprobe on PATH (override with $FFPROBE).
 */
import { spawnSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VOICE = path.join(ROOT, 'public', 'voice');
const OUT = path.join(ROOT, 'src', 'pacer', 'clipdurations.ts');
const FFPROBE = process.env.FFPROBE || 'ffprobe';

const files = readdirSync(VOICE).filter((f) => /\.(ogg|wav)$/.test(f)).sort();
const out = {};
for (const f of files) {
  const r = spawnSync(FFPROBE, ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path.join(VOICE, f)], {
    encoding: 'utf8',
  });
  const seconds = Number.parseFloat(r.stdout);
  if (r.status !== 0 || !Number.isFinite(seconds)) {
    console.error(`clip-durations: could not measure ${f}: ${r.stderr || r.error?.message || 'no output'}`);
    process.exit(1);
  }
  out[`/voice/${f}`] = Math.round(seconds * 100) / 100;
}

const lines = [
  '/**',
  ' * GENERATED by scripts/clip-durations.mjs — do not edit.',
  ' * Seconds of audio in every recorded voice clip, so the class can start',
  ' * a movement when its line has finished being said.',
  ' */',
  'export const clipDurations: Record<string, number> = {',
  ...Object.entries(out).map(([k, v]) => `  '${k}': ${v},`),
  '};',
  '',
];
writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`clip-durations: ${files.length} clips → ${path.relative(ROOT, OUT)}`);
