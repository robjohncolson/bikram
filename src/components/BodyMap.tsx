/* ------------------------------------------------------------------ geometry
 * Everything is drawn in a 0 0 120 260 viewBox, centered on x = 60.
 * Paired regions are authored for the viewer-right side only and the
 * left side is generated by mirroring across x = 60, so the two sides
 * always match exactly. Path strings use ONLY absolute `M x y`,
 * `C x1 y1 x2 y2 x y` and `Z` commands with single-space separated
 * numbers — the tiny mirror() parser below depends on that format.
 */

const VIEW_W = 120;
const VIEW_H = 260;

const fmt = (n: number) => String(Math.round(n * 100) / 100);

/** Mirror an M/C/Z path across the vertical centerline x = 60. */
function mirror(d: string): string {
  let isX = true;
  return d
    .split(' ')
    .map((token) => {
      if (token === 'M' || token === 'C') {
        isX = true;
        return token;
      }
      if (token === 'Z') return token;
      const out = isX ? fmt(VIEW_W - Number(token)) : token;
      isX = !isX;
      return out;
    })
    .join(' ');
}

/** Author the right side, get both sides as one path (two subpaths). */
const sym = (d: string) => `${d} ${mirror(d)}`;

