/* ------------------------------------------------------------------ component */

type FigureSide = 'front' | 'back';

function musclesFor(side: FigureSide): MuscleGroup[] {
  return muscles.filter(
    (m) => (m.view === 'both' || m.view === side) && REGION_PATHS[m.id]?.[side],
  );
}

function describe(
  side: FigureSide,
  shown: MuscleGroup[],
  highlights: Partial<Record<MuscleId, MuscleHighlight>>,
): string {
  const list = (kind: MuscleHighlight) =>
    shown.filter((m) => highlights[m.id] === kind).map((m) => m.name);
  const strengthens = list('strengthens');
  const stretches = list('stretches');
  const label = side === 'front' ? 'Front' : 'Back';
  const parts: string[] = [];
  if (strengthens.length) parts.push(`strengthens ${strengthens.join(', ')}`);
  if (stretches.length) parts.push(`stretches ${stretches.join(', ')}`);
  return parts.length ? `${label} of body: ${parts.join('; ')}` : `${label} of body`;
}

export function BodyMap({
  highlights = {},
  selected = null,
  onSelect,
  view = 'both',
  height = 300,
}: BodyMapProps) {
  const sides: FigureSide[] = view === 'both' ? ['front', 'back'] : [view];
  const interactive = onSelect !== undefined;
  const width = Math.round((height * VIEW_W) / VIEW_H);

  return (
    <div className={`bodymap${interactive ? ' bodymap--interactive' : ''}`}>
      {sides.map((side) => {
        const shown = musclesFor(side);
        return (
          <div key={side} className="bodymap-figure">
            <svg
              className="bodymap-svg"
              viewBox={`0 0 ${VIEW_W} ${VIEW_H}`}
              width={width}
              height={height}
              role={interactive ? 'group' : 'img'}
              aria-label={
                interactive
                  ? `${side === 'front' ? 'Front' : 'Back'} of body: choose a muscle group`
                  : describe(side, shown, highlights)
              }
            >
              <path className="bodymap-silhouette" d={SILHOUETTE} aria-hidden="true" />
              {shown.map((m) => {
                const d = REGION_PATHS[m.id][side];
                if (!d) return null;
                const hl = highlights[m.id];
                const isSelected = selected === m.id;
                const handleKey = (e: KeyboardEvent<SVGPathElement>) => {
                  if (e.key === 'Enter' || e.key === ' ') {
                    e.preventDefault();
                    onSelect?.(m.id);
                  }
                };
                return (
                  <path
                    key={m.id}
                    d={d}
                    className={`bodymap-region${isSelected ? ' bodymap-region--selected' : ''}`}
                    data-hl={hl}
                    role={interactive ? 'button' : undefined}
                    tabIndex={interactive ? 0 : undefined}
                    aria-pressed={interactive ? isSelected : undefined}
                    onClick={interactive ? () => onSelect?.(m.id) : undefined}
                    onKeyDown={interactive ? handleKey : undefined}
                  >
                    <title>{m.name}</title>
                  </path>
                );
              })}
            </svg>
            {view === 'both' && (
              <span className="bodymap-figure-label" aria-hidden="true">
                {side === 'front' ? 'Front' : 'Back'}
              </span>
            )}
          </div>
        );
      })}
    </div>
  );
}
